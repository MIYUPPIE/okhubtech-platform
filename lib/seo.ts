import type { Metadata } from "next";

import { EMAIL, FACEBOOK, INSTAGRAM, LOCATION, PHONE_E164 } from "./contact";
import { YOUTUBE_CHANNEL } from "./bootcamp";

/**
 * Single builder for every page's <title>, description, canonical link, and
 * social-share card.
 *
 * Why this exists: before it, ~28 of the site's ~40 routes had no metadata of
 * their own and silently inherited the root layout's. Sharing /services/networking,
 * /expertise/robotics, or any of eight portfolio pages on WhatsApp, Twitter or
 * LinkedIn showed the exact same title, description AND image as the homepage -
 * the visitor had no way to tell which page they were looking at before clicking.
 * scripts/verify-seo.mjs fails the build if any indexable route's rendered
 * og:title/og:description/og:image trio still matches the homepage's.
 *
 * Every field funnels through here so canonical, og:*, twitter:* and robots
 * can never drift from each other on a given page - set title and description
 * once, get a complete, internally consistent Metadata object back.
 */

export const SITE_NAME = "OKHub Technology";

/** `title.template` on the root layout appends this; pass only the short form here. */
export const TITLE_SUFFIX = `${SITE_NAME}`;

/**
 * An OG card generated by scripts/build_media.py into public/media/og/<slug>.png.
 * 1200x630 is the size every major platform (Twitter, LinkedIn, WhatsApp,
 * Facebook, Slack, Discord) reads without cropping or upscaling.
 */
export function ogImage(slug: string, alt: string) {
  return [{ url: `/media/og/${slug}.png`, width: 1200, height: 630, alt }];
}

export type PageMetadataInput = {
  /** Site-root path, no trailing slash ("" for the home page). */
  path: string;
  /** Short form - the root layout's title template appends " | OKHub Technology". */
  title: string;
  /** Rendered as-is in <meta name="description">, og:description and twitter:description. Keep it under ~160 characters so platforms do not truncate it mid-sentence. */
  description: string;
  /** Slug of a card built by build_media.py's OG_CARDS list. Falls back to the site default when omitted or undefined. */
  ogSlug?: string | undefined;
  /** Alt text for the share image. Required whenever ogSlug is set - screen readers and platforms that fail to load the image both need it. */
  ogAlt?: string | undefined;
  /** Keeps the page out of search results and off the sitemap's implied index, without touching robots.txt (which only stops crawling, not indexing of an already-linked URL) or PUBLIC_ROUTES (which drives the sitemap itself). */
  noindex?: boolean;
  /** "article" for something with a publish date/author; every page on this site is "website". */
  type?: "website" | "article";
};

export function pageMetadata({
  path,
  title,
  description,
  ogSlug,
  ogAlt,
  noindex = false,
  type = "website",
}: PageMetadataInput): Metadata {
  const url = path === "" ? "/" : path;
  const images = ogSlug !== undefined ? ogImage(ogSlug, ogAlt ?? title) : undefined;

  return {
    // `absolute` composes the full title here rather than leaning on the root
    // layout's title.template. Next only threads that template through when
    // no metadata between root and the leaf sets its own title as a plain
    // string; app/portfolio/layout.tsx does exactly that (it has to - the
    // page beneath it is a client component and cannot export metadata of
    // its own), which silently dropped " | OKHub Technology" off every one
    // of the twelve portfolio pages nested under it. Composing the full
    // string here makes every page's title correct regardless of what
    // layouts sit above it in the tree.
    title: { absolute: `${title} | ${SITE_NAME}` },
    description,
    alternates: { canonical: url },
    ...(noindex ? { robots: { index: false, follow: false } } : {}),
    openGraph: {
      title,
      description,
      url,
      siteName: SITE_NAME,
      images,
      locale: "en_US",
      type,
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: images?.map((i) => i.url),
    },
  };
}

/**
 * For pages that must never be indexed or shared: /admin, /login, /register,
 * /unauthorized. robots.txt already disallows crawling these; this is the
 * second, independent layer - a page a crawler reaches by any other route
 * (a stale link, a browser bookmark someone shared) still carries the
 * instruction not to index it, which robots.txt alone cannot guarantee.
 */
export function noindexMetadata(title: string): Metadata {
  return {
    title,
    robots: { index: false, follow: false },
  };
}

/**
 * Organization schema (JSON-LD), rendered once in the root layout. This is
 * what lets Google show a knowledge-panel-style result (logo, verified
 * social profiles, contact point) rather than a bare blue link, and is the
 * only place the sameAs profile list needs to stay correct.
 */
export function organizationJsonLd(siteUrl: string) {
  return {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: SITE_NAME,
    url: siteUrl,
    logo: `${siteUrl}/media/brand/okhub-wordmark-dark.png`,
    email: EMAIL,
    telephone: PHONE_E164,
    address: {
      "@type": "PostalAddress",
      addressLocality: "Ibadan",
      addressRegion: "Oyo State",
      addressCountry: "NG",
      streetAddress: LOCATION,
    },
    sameAs: [YOUTUBE_CHANNEL, INSTAGRAM, FACEBOOK],
  };
}

export function websiteJsonLd(siteUrl: string) {
  return {
    "@context": "https://schema.org",
    "@type": "WebSite",
    name: SITE_NAME,
    url: siteUrl,
  };
}

export type BreadcrumbItem = { name: string; path: string };

/** Renders as a BreadcrumbList so Search can show the path segments (Home > Services > Networking) instead of a bare URL in results. */
export function breadcrumbJsonLd(siteUrl: string, items: readonly BreadcrumbItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: `${siteUrl}${item.path === "" ? "/" : `${item.path}/`}`,
    })),
  };
}
